class LocalizationManager:
    """Manages active language, system locale detection, and string lookup."""

    _instance: Optional['LocalizationManager'] = None

    def __new__(cls):
        if cls._instance is None:
            cls._instance = super(LocalizationManager, cls).__new__(cls)
            cls._instance._init()
        return cls._instance

    def _init(self):
        self._active_language = self.detect_system_language()

    @staticmethod
    def detect_system_language() -> str:
        """Detects if Windows is configured in Russian or defaults to English."""
        if sys.platform == "win32":
            try:
                lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()
                # Primary language ID for Russian is 0x19 (0x0419)
                if (lang_id & 0xFF) == 0x19:
                    return "ru"
            except Exception:
                pass
        try:
            loc = locale.getlocale()[0]
            if loc and "ru" in loc.lower():
                return "ru"
        except Exception:
            pass
        return "en"

    def set_language(self, lang: str):
        """Sets active language: 'auto', 'ru', or 'en'."""
        if lang == "auto":
            self._active_language = self.detect_system_language()
        elif lang in ("ru", "en"):
            self._active_language = lang
        else:
            self._active_language = "ru"

    @property
    def current_language(self) -> str:
        return self._active_language

    @property
    def current_lang(self) -> str:
        """Alias for current_language."""
        return self._active_language

    def tr(self, key: str, default: Optional[str] = None, **kwargs) -> str:
        """Translates key into the active language with optional format parameters."""
        lang_dict = TRANSLATIONS.get(self._active_language, TRANSLATIONS["ru"])
        text = lang_dict.get(key)
        if text is None:
            # Fallback to Russian then English
            text = TRANSLATIONS["ru"].get(key, TRANSLATIONS["en"].get(key, default or key))
        if kwargs:
            try:
                return text.format(**kwargs)
            except Exception:
                return text
        return text


# Global singleton helper
_i18n = LocalizationManager()

def tr(key: str, default: Optional[str] = None, **kwargs) -> str:
    """Global translation helper function."""
    return _i18n.tr(key, default=default, **kwargs)

def get_i18n() -> LocalizationManager:
    return _i18n
